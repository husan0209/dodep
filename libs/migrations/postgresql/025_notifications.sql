-- Migration 025: Notification Service tables (centralised DDL contract)
--
-- Source of truth (mirrored, not modified):
--   services/go/notification/internal/repository/notification_repository.go
--   (DDL contract comment + Notification / NotificationSettings structs +
--   GetUserNotifications / GetUnreadCount / GetPendingNotifications queries).
--
-- Tables:
--   notifications          - one row per outbound notification (all channels)
--   notification_settings  - one row per user (PK = user_id, i.e. UNIQUE(user_id))
--
-- Column notes (verified against the repository):
--   - type / is_read / status columns exist exactly as the repository queries
--     them (filters in GetUserNotifications, GetUnreadCount, MarkAsRead).
--   - There is NO separate `payload` column in the repository contract.
--     Service-level payloads (WSEvent.Payload for the WS gateway, the Redis
--     cache envelope) are stored in the `data` and `metadata` JSONB columns.
--   - Money never appears here (no amounts stored, per repository contract).
--   - user_id is BIGINT; id is TEXT (opaque string key generated by the service).
--
-- Conventions:
--   - Idempotent: IF NOT EXISTS / DROP TRIGGER IF EXISTS, safe to re-run.
--   - No CONCURRENTLY: applied inside a transaction pre-launch, same rule as
--     024_stage3_hardening.sql. Post-launch index work must use CONCURRENTLY
--     in a separate migration outside a transaction.
--   - updated_at maintenance reuses update_updated_at() owned by
--     001_extensions_and_enums.sql (no duplicate function definition).

BEGIN;

CREATE TABLE IF NOT EXISTS notifications (
    id TEXT PRIMARY KEY,
    user_id BIGINT NOT NULL,
    channel TEXT NOT NULL DEFAULT '',
    type TEXT NOT NULL DEFAULT '',
    priority TEXT NOT NULL DEFAULT 'normal',
    subject TEXT NOT NULL DEFAULT '',
    message TEXT NOT NULL DEFAULT '',
    data JSONB NOT NULL DEFAULT '{}'::jsonb,
    is_read BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    read_at TIMESTAMPTZ,
    sent_at TIMESTAMPTZ,
    status TEXT NOT NULL DEFAULT 'pending',
    error_message TEXT NOT NULL DEFAULT '',
    reference_id TEXT NOT NULL DEFAULT '',
    metadata JSONB NOT NULL DEFAULT '{}'::jsonb
);

CREATE TABLE IF NOT EXISTS notification_settings (
    user_id BIGINT PRIMARY KEY,
    email_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    sms_enabled BOOLEAN NOT NULL DEFAULT FALSE,
    push_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    in_app_enabled BOOLEAN NOT NULL DEFAULT TRUE,
    type_preferences JSONB NOT NULL DEFAULT '{}'::jsonb,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

-- History lookup: WHERE user_id = $1 [AND ...] ORDER BY created_at DESC
-- (GetUserNotifications, cursor pagination).
CREATE INDEX IF NOT EXISTS idx_notifications_user
    ON notifications (user_id, created_at DESC);

-- Unread counter / bulk-read: WHERE user_id = $1 AND is_read = FALSE
-- (GetUnreadCount, MarkAllAsRead). Partial: read rows are never matched.
CREATE INDEX IF NOT EXISTS idx_notifications_unread
    ON notifications (user_id, created_at DESC)
    WHERE is_read = FALSE;

-- Dispatch sweep: WHERE status = 'pending' ORDER BY created_at ASC
-- (GetPendingNotifications). Partial: only pending rows are indexed.
CREATE INDEX IF NOT EXISTS idx_notifications_pending
    ON notifications (status, created_at ASC)
    WHERE status = 'pending';

-- Settings upsert is ON CONFLICT (user_id); the PRIMARY KEY already enforces
-- UNIQUE(user_id), no extra index needed.

-- Auto-maintain notification_settings.updated_at on every UPDATE
-- (upserts from UpdateNotificationSettings set updated_at = NOW() explicitly;
-- this trigger covers any other write path).
DROP TRIGGER IF EXISTS trg_notification_settings_updated_at ON notification_settings;
CREATE TRIGGER trg_notification_settings_updated_at
    BEFORE UPDATE ON notification_settings
    FOR EACH ROW EXECUTE FUNCTION update_updated_at();

COMMIT;
